'use strict';

const fs = require('fs');
const path = require('path');
const pluginCompat = require('./plugin-compat');

const GENERATED_MARKER = '<!-- Generated by codex-ollama-proxy computer-use bridge. -->';
const COMPUTER_USE = pluginCompat.findPlugin('computer-use@openai-bundled');

function versionDirs(root) {
  let entries;
  try { entries = fs.readdirSync(root, { withFileTypes: true }); } catch { return []; }
  return entries
    .filter((entry) => entry.isDirectory())
    .map((entry) => path.join(root, entry.name))
    .sort((a, b) => path.basename(b).localeCompare(path.basename(a), undefined, { numeric: true }));
}

function runtimeAt(pluginRoot) {
  const bootstrapPath = path.join(pluginRoot, ...COMPUTER_USE.bootstrapRelativePath);
  const sourceSkillPath = path.join(pluginRoot, ...COMPUTER_USE.sourceSkillRelativePath);
  if (!fs.existsSync(bootstrapPath) || !fs.existsSync(sourceSkillPath)) return null;
  return {
    pluginRoot: fs.realpathSync(pluginRoot),
    bootstrapPath: fs.realpathSync(bootstrapPath),
    sourceSkillPath: fs.realpathSync(sourceSkillPath),
  };
}

function resolveComputerUseRuntime(codexDir) {
  const roots = COMPUTER_USE.runtimeRoots.map((parts) => path.join(codexDir, ...parts));
  for (const root of roots) {
    const direct = runtimeAt(root);
    if (direct) return direct;
    for (const candidate of versionDirs(root)) {
      const runtime = runtimeAt(candidate);
      if (runtime) return runtime;
    }
  }
  return null;
}

function bridgeInstructions(bootstrapPath) {
  return `${GENERATED_MARKER}

## Local-model compatibility bridge

- \`${COMPUTER_USE.pluginId}\` is a plugin identifier, not a URL, plugin link, MCP server name, or callable tool.
- Computer Use operates through the deferred \`${COMPUTER_USE.discoveryQuery}\` tool. If it is not callable yet, call \`tool_search\` with exactly \`{"query":${JSON.stringify(COMPUTER_USE.discoveryQuery)}}\`, then invoke the exact callable name returned by that search.
- Do not import \`${COMPUTER_USE.directImportPackage}\` directly and do not copy unresolved placeholder paths.
- Initialize each fresh \`node_repl\` session with this resolved bootstrap:

\`\`\`js
if (!globalThis.sky) {
  const { setupComputerUseRuntime } = await import(${JSON.stringify(bootstrapPath)});
  await setupComputerUseRuntime({ globals: globalThis });
}
\`\`\`
`;
}

function renderCompatibilitySkill(source, bootstrapPath) {
  const resolvedSource = String(source).replaceAll(
    COMPUTER_USE.sourceRootPlaceholder,
    path.dirname(path.dirname(bootstrapPath))
  );
  const frontmatter = /^(---\r?\n[\s\S]*?\r?\n---\r?\n?)/.exec(resolvedSource);
  if (!frontmatter) throw new Error('Computer Use SKILL.md has no valid frontmatter');
  return frontmatter[1] + '\n' + bridgeInstructions(bootstrapPath) + '\n' + resolvedSource.slice(frontmatter[1].length);
}

function installCompatibilitySkill(options = {}) {
  const codexDir = path.resolve(options.codexDir || path.join(process.env.HOME, '.codex'));
  const runtime = resolveComputerUseRuntime(codexDir);
  if (!runtime) return { status: 'runtime_missing' };

  const destination = path.join(codexDir, ...COMPUTER_USE.stableSkillRelativePath);
  let existing = null;
  try { existing = fs.readFileSync(destination, 'utf8'); } catch {}
  if (existing != null && !existing.includes(GENERATED_MARKER)) {
    return { status: 'conflict', destination, runtime };
  }

  const source = fs.readFileSync(runtime.sourceSkillPath, 'utf8');
  const rendered = renderCompatibilitySkill(source, runtime.bootstrapPath);
  if (existing === rendered) return { status: 'current', destination, runtime };

  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.writeFileSync(destination, rendered, 'utf8');
  return { status: existing == null ? 'created' : 'updated', destination, runtime };
}

module.exports = {
  GENERATED_MARKER,
  installCompatibilitySkill,
  renderCompatibilitySkill,
  resolveComputerUseRuntime,
};
